"""Builds assets/map/world.json, the world map's land, from Natural Earth.

Natural Earth (https://www.naturalearthdata.com) is public domain. Download
ne_50m_admin_0_countries.geojson and ne_50m_lakes.geojson from
https://github.com/nvkelso/natural-earth-vector/tree/master/geojson, then:

    pip install shapely
    python3 tool/build_map.py <folder with the geojson files>

Countries are merged into the game's 7 regions, simplified at two levels of
detail with shared edges kept identical, and written as integer hundredths of
a degree. See docs/world-map.md.
"""

import json
import sys
from pathlib import Path

import shapely
from shapely.geometry import Point, box, shape
from shapely.ops import unary_union

CONTINENTS = {
    'North America': 'north_america',
    'South America': 'south_america',
    'Europe': 'europe',
    'Africa': 'africa',
    'Asia': 'asia',
    'Oceania': 'oceania',
    'Antarctica': 'antarctica',
}

# Coordinates are kept to 1/SCALE of a degree; simplification tolerances in degrees.
SCALE = 100
LODS = {'detail': 0.06, 'coarse': 0.3}
# Islands smaller than this (square degrees) are dropped at each level.
MIN_AREA = {'detail': 0.05, 'coarse': 0.6}
# Lakes big enough to show on a world map.
LAKE_MIN_AREA = 1.5


def geo_region(lon, lat):
    """Rough region for a small island far from its country's continent."""
    if lat < -60:
        return 'antarctica'
    if -170 <= lon <= -30:
        return 'north_america' if lat > 12 or (lon < -78 and lat > 7) else 'south_america'
    if -30 < lon < -10:
        return 'europe' if lat > 30 else 'africa'
    if lon > 140 or lon < -170:
        return 'oceania' if lat < 0 else 'asia'
    if lon > 110 and lat < -10:
        return 'oceania'
    if lon < 65 and lat < 12:
        return 'africa'
    if lon < 45 and lat > 36:
        return 'europe'
    return 'asia'


def region_parts(feature):
    props = feature['properties']
    code = props['ADM0_A3']
    home = CONTINENTS.get(props['CONTINENT'])
    geom = shape(feature['geometry']).buffer(0)
    if code == 'RUS':
        # The Urals split Russia between Europe and Asia.
        yield 'europe', geom.intersection(box(-180, -90, 60, 90))
        yield 'asia', geom.intersection(box(60, -90, 180, 90))
        return
    if code == 'TUR':
        yield 'europe', geom
        return
    polys = list(geom.geoms) if geom.geom_type == 'MultiPolygon' else [geom]
    mainland = max(polys, key=lambda p: p.area)
    for p in polys:
        c = p.representative_point()
        # Overseas parts (French Guiana, Caribbean Netherlands) go by where
        # they are; Hawaii stays with the USA, as in cities.json.
        far = p is not mainland and p.distance(mainland) > 8
        if home is None or (far and code != 'USA'):
            yield geo_region(c.x, c.y), p
        else:
            yield home, p


def polygons(geom):
    if geom.is_empty:
        return []
    if geom.geom_type == 'Polygon':
        return [geom]
    return [g for g in getattr(geom, 'geoms', []) if g.geom_type == 'Polygon']


def lines(geom):
    if geom.is_empty:
        return []
    if geom.geom_type in ('LineString', 'LinearRing'):
        return [geom]
    out = []
    for g in getattr(geom, 'geoms', []):
        out.extend(lines(g))
    return out


def flat(coords):
    out = []
    last = None
    for x, y in coords:
        p = (round(x * SCALE), round(y * SCALE))
        if p != last:
            out.extend(p)
            last = p
    return out


def polygon_json(p):
    rings = [flat(p.exterior.coords)] + [flat(r.coords) for r in p.interiors]
    return [r for r in rings if len(r) >= 6]


def main(folder):
    folder = Path(folder)
    cities = json.loads(
        (Path(__file__).resolve().parent.parent / 'assets' / 'data' / 'cities.json').read_text()
    )['cities']
    city_points = [Point(c['lon'], c['lat']) for c in cities]
    countries = json.loads((folder / 'ne_50m_admin_0_countries.geojson').read_text())
    lakes_src = json.loads((folder / 'ne_50m_lakes.geojson').read_text())

    world_box = box(-180, -90, 180, 84)
    by_region = {r: [] for r in CONTINENTS.values()}
    for f in countries['features']:
        for region, geom in region_parts(f):
            by_region[region].append(geom)
    ids = list(CONTINENTS.values())
    merged = [unary_union(by_region[r]).intersection(world_box) for r in ids]

    lakes = [shape(f['geometry']).buffer(0) for f in lakes_src['features']]
    lakes = unary_union([l for l in lakes if l.area >= LAKE_MIN_AREA])

    out = {
        '_note': 'Generated by tool/build_map.py from Natural Earth 1:50m (public domain). '
        'Coordinates are [lon, lat, lon, lat, ...] in hundredths of a degree.',
        'scale': SCALE,
        'regionIds': ids,
        'lods': {},
    }
    for lod, tol in LODS.items():
        simple = shapely.coverage_simplify(merged, tol)
        def keep(p):
            # Small islands go, unless a city is on them (Honolulu, Suva).
            return p.area >= MIN_AREA[lod] or any(p.distance(c) < 0.3 for c in city_points)

        simple = [unary_union([p for p in polygons(g) if keep(p)]) for g in simple]
        land = unary_union(simple)
        # The map's own edges (the date line, the pole, the northern cut) are
        # not coastline.
        edges = world_box.boundary.buffer(0.01)
        coast = lines(shapely.line_merge(land.boundary.difference(edges)))
        borders = []
        for i in range(len(simple)):
            for j in range(i + 1, len(simple)):
                shared = simple[i].boundary.intersection(simple[j].boundary)
                borders.extend(lines(shapely.line_merge(shared)) if not shared.is_empty else [])
        lake_polys = polygons(lakes.simplify(tol))
        out['lods'][lod] = {
            'regions': {
                rid: [polygon_json(p) for p in polygons(g)] for rid, g in zip(ids, simple)
            },
            'coast': [flat(l.coords) for l in coast],
            'borders': [flat(l.coords) for l in borders if l.length > 0.5],
            'lakes': [polygon_json(p) for p in lake_polys],
        }
        points = sum(len(r) // 2 for g in out['lods'][lod]['regions'].values() for p in g for r in p)
        print(f'{lod}: {points} region points, {len(coast)} coast lines, {len(borders)} borders')

    target = Path(__file__).resolve().parent.parent / 'assets' / 'map' / 'world.json'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(out, separators=(',', ':')))
    print(f'wrote {target} ({target.stat().st_size // 1024} KB)')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '.')
